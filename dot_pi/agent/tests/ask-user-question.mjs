import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
const piDir = process.env.PI_CODING_AGENT_PACKAGE ?? resolve(dirname(process.execPath), '../lib/node_modules/@earendil-works/pi-coding-agent');
const {loadExtensions} = await import(pathToFileURL(resolve(piDir, 'dist/core/extensions/loader.js')));
const entry = resolve(dirname(fileURLToPath(import.meta.url)), '../extensions/ask-user-question.ts');
const r = await loadExtensions([entry], process.cwd());
assert.deepEqual(r.errors, []);
const tool = r.extensions[0].tools.get('ask_user_question').definition;
const params = {question:'Fixture question',options:[{label:'One'}]};
const call = (args, ctx, signal) => tool.execute('fixture', args, signal, undefined, ctx);
const ctx = {hasUI:true,mode:'tui',ui:{custom:async()=>null,editor:async()=> ' text '}};
assert.equal((await call(params,{...ctx,hasUI:false})).details.status,'unavailable');
assert.equal((await call(params,{...ctx,mode:'rpc'})).details.status,'unavailable');
assert.equal((await call({...params,multiSelect:true},{...ctx,mode:'rpc'})).details.status,'unavailable');
assert.equal((await call({question:'Text'},{...ctx,mode:'rpc'})).details.answers[0].value,'text');
assert.equal((await call(params,ctx)).details.status,'cancelled');
const answer = {type:'option',label:'One',value:'One',index:1};
assert.equal((await call(params,{...ctx,ui:{custom:async()=>answer}})).details.answers[0].value,'One');
assert.equal((await call({...params,multiSelect:true},{...ctx,ui:{custom:async()=>[answer]}})).details.mode,'multi-select');
const other = {type:'other',label:'Custom',value:'Custom'};
assert.equal((await call(params,{...ctx,ui:{custom:async()=>other}})).details.answers[0].type,'other');
const abort = new AbortController(); abort.abort();
assert.equal((await call(params,ctx,abort.signal)).details.status,'cancelled');
let release;
const first = call({question:'First'}, {...ctx,ui:{editor:()=>new Promise(r=>{release=r;})}});
await new Promise(r=>setImmediate(r));
const queuedAbort = new AbortController(); let opened=false;
const second = call({question:'Second'}, {...ctx,ui:{editor:async()=>{opened=true;return 'bad';}}}, queuedAbort.signal);
queuedAbort.abort(); release('done');
await first;
assert.equal((await second).details.status,'cancelled');
assert.equal(opened,false);
const during = new AbortController();
assert.equal((await call({question:'Late'}, {...ctx,ui:{editor:async()=>{during.abort();return 'late answer';}}},during.signal)).details.status,'cancelled');
console.log('PASS: 12 question-flow checks. UI responses mocked; no keyboard/rendering tests.');
